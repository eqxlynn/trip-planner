const fs = require('fs');
const path = require('path');

const env = {
    GOOGLE_CLIENT_ID: (process.env.GOOGLE_CLIENT_ID || '').trim(),
    GOOGLE_API_KEY: (process.env.GOOGLE_API_KEY || '').trim(),
};

const target = path.join(__dirname, '..', 'js', 'core', 'env.js');
const content = `// Auto-generated by scripts/build-env.js\nwindow.__ENV__ = ${JSON.stringify(env, null, 4)};\n`;

fs.writeFileSync(target, content, 'utf8');
console.log('Generated js/core/env.js');
